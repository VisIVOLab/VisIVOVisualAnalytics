#!/usr/bin/env python
"""Regenerate the client<->backend contract snapshots.

Run this after an *intentional* API change (new/renamed/removed route, or a new
``X-*`` response header) so the committed snapshots match the live app again:

    backend/.venv/bin/python backend/scripts/gen_contract.py

It writes:
  * backend/tests/contract/openapi_routes.json  — every (METHOD PATH) route
  * backend/tests/contract/visivo_headers.json  — every declared X-* header name
  * docs/contract/visivo_headers.json           — a discoverable mirror
  * src/app/BackendHeaders.h                     — the C++ mirror of the names

``backend/tests/test_contract.py`` fails whenever the live app drifts from these,
so an accidental drop (the past "router refactor dropped endpoints" incident) is
caught in CI instead of at runtime in the desktop client.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
REPO = BACKEND.parent
sys.path.insert(0, str(BACKEND))


def route_list() -> list[str]:
    from app.main import app  # noqa: PLC0415

    schema = app.openapi()
    return sorted(
        f"{method.upper()} {path}"
        for path, ops in schema.get("paths", {}).items()
        for method in ops
        if method.lower() in ("get", "post", "put", "patch", "delete")
    )


def header_list() -> list[str]:
    from app.response_headers import KNOWN_RESPONSE_HEADERS  # noqa: PLC0415

    return sorted(KNOWN_RESPONSE_HEADERS)


def _cpp_ident(header: str) -> str:
    ident = header.replace("X-Visivo-", "").replace("X-", "").replace("-", "_").upper()
    # Avoid identifiers that collide with system preprocessor macros (the macro
    # would expand before the namespace is seen). BYTE_ORDER is defined by
    # <sys/_endian.h> on Apple platforms.
    _COLLISIONS = {"BYTE_ORDER": "BYTEORDER"}
    return _COLLISIONS.get(ident, ident)


def write_cpp_header(headers: list[str]) -> None:
    lines = [
        "// AUTO-GENERATED by backend/scripts/gen_contract.py — DO NOT EDIT BY HAND.",
        "// Canonical names of the X-* HTTP headers exchanged with the VisIVO backend.",
        "// Single source of truth: backend/tests/contract/visivo_headers.json",
        "// (mirrors backend/app/response_headers.py). Regenerate after an API change:",
        "//   backend/.venv/bin/python backend/scripts/gen_contract.py",
        "//",
        "// The desktop client reads binary-endpoint metadata (units, geometry, ranges)",
        '// from these headers; a silent rename/drop would otherwise read as 0/"".',
        "// TestBackendContract asserts this set equals the manifest, catching drift.",
        "#pragma once",
        "",
        "#include <array>",
        "",
        "namespace VisivoHeaders {",
    ]
    for h in headers:
        lines.append(f'inline constexpr const char *{_cpp_ident(h)} = "{h}";')
    lines.append("")
    lines.append("// Every declared header name, for the contract test to diff against the manifest.")
    lines.append(f"inline constexpr std::array<const char *, {len(headers)}> kAll = {{")
    for h in headers:
        lines.append(f"    {_cpp_ident(h)},")
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace VisivoHeaders")
    (REPO / "src/app/BackendHeaders.h").write_text("\n".join(lines) + "\n")


def main() -> None:
    routes = route_list()
    (BACKEND / "tests/contract/openapi_routes.json").write_text(
        json.dumps(
            {
                "_comment": "Snapshot of (METHOD PATH) routes from app.openapi(). "
                "test_contract.py fails on drift. Regenerate with "
                "backend/scripts/gen_contract.py after an intentional API change.",
                "routes": routes,
            },
            indent=2,
        )
        + "\n"
    )
    headers = header_list()
    manifest = {
        "_comment": "Single source of truth for VisIVO X-* HTTP header names. "
        "Python: backend/app/response_headers.py. C++: src/app/BackendHeaders.h. "
        "Both contract tests assert equality with this file.",
        "headers": headers,
    }
    (BACKEND / "tests/contract/visivo_headers.json").write_text(
        json.dumps(manifest, indent=2) + "\n"
    )
    (REPO / "docs/contract/visivo_headers.json").write_text(
        json.dumps(manifest, indent=2) + "\n"
    )
    write_cpp_header(headers)
    print(f"wrote {len(routes)} routes and {len(headers)} headers (+ C++ mirror)")


if __name__ == "__main__":
    main()
